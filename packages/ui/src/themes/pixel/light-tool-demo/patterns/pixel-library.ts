/** Find a pattern by id. */
export function getPixelPattern(id: string): PixelPattern | undefined {
  return PIXEL_PATTERNS.find((p) => p.id === id);
}

/** Patterns suited to a craft, in library order. */
export function patternsForCraft(craft: PixelCraft): PixelPattern[] {
  return PIXEL_PATTERNS.filter((p) => p.crafts.includes(craft));
}

/* ── Grid stats + rendering (pure, no DOM) ─────────────────────────────── */

export interface PatternStats {
  cols: number;
  rows: number;
  /** hex -> cell count, sorted by count desc. */
  counts: { hex: string; count: number }[];
  totalCells: number;
}

export function patternStats(pattern: PixelPattern): PatternStats {
  const rows = pattern.grid.length;
  const cols = pattern.grid[0]?.length ?? 0;
  const counts = new Map<string, number>();
  let totalCells = 0;
  for (const row of pattern.grid) {
    for (const ch of row) {
      if (ch === '.' || ch === ' ') continue;
      const hex = pattern.palette[ch];
      if (!hex) continue;
      counts.set(hex, (counts.get(hex) ?? 0) + 1);
      totalCells++;
    }
  }
  return {
    cols,
    rows,
    totalCells,
    counts: [...counts.entries()]
      .map(([hex, count]) => ({ hex, count }))
      .sort((a, b) => b.count - a.count),
  };
}
