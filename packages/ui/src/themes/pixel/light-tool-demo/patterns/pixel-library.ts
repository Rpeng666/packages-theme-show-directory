/**
 * Pixel pattern library - the shared "real designs" asset for the tool pages.
 *
 * Every pattern is a hand-drawn pixel design (ASCII grid + palette), tagged
 * with the crafts it suits. This replaces the math-generated stripes/checkers
 * that made the generator demos look programmer-made: a user landing on a
 * craft tool page sees an actual finished artifact within 3 seconds.
 *
 * Grid rows must all be the same width; palette maps a char -> hex. '.' is
 * always transparent.
 */

export type PixelCraft = 'bead' | 'cross-stitch' | 'bracelet' | 'diamond' | 'knitting' | 'sprite';
export type PatternCategory = 'animal' | 'nature' | 'food' | 'symbol' | 'game';

export interface PixelPattern {
  id: string;
  name: string;
  category: PatternCategory;
  difficulty: 'easy' | 'medium';
  crafts: PixelCraft[];
  palette: Record<string, string>;
  grid: string[];
}

